/**
 * บิลประจำรายเดือน (ยอดคงที่ ครบกำหนดวันเดียวกันทุกเดือน) ยอดเป็นสตางค์จำนวนเต็มเสมอ (กฎ R1)
 * จ่ายบิลได้ครั้งเดียวต่อรอบ: เก็บ lastPaidMonth ไว้ตามกฎ R15
 */
export interface Bill {
  id: string;
  name: string;
  /** สตางค์ จำนวนเต็มบวก */
  amount: number;
  /** วันครบกำหนดในเดือน 1-31 (เกินจำนวนวันของเดือนจะครบกำหนดวันสุดท้ายของเดือน) */
  dueDay: number;
  /** กระเป๋าที่จ่าย (ไม่บังคับ) */
  walletId?: string;
  /** หมวดรายจ่าย (ไม่บังคับ) */
  categoryId?: string;
  /** รอบเดือนล่าสุดที่จ่ายแล้ว YYYY-MM (เก็บเป็นค่าเดียว ไม่ใช่ประวัติ) */
  lastPaidMonth?: string;
  /**
   * เดือนที่ตั้งบิลนี้ YYYY-MM ใช้จำกัดการนับหนี้ค้างย้อนหลัง: ไม่ระบุ = ไม่นับย้อนหลังเลย
   * (บิลที่เพิ่งสร้างไม่ถูกมองว่าค้างมาก่อน) ระบุ = นับรอบเดือนก่อนที่ยังไม่จ่ายได้ไม่เกิน 1 เดือน
   */
  startMonth?: string;
  archived?: boolean;
}

/** บิลที่ยังไม่จ่ายและครบกำหนดภายในช่วงที่ถาม */
export interface UpcomingBill {
  bill: Bill;
  /** YYYY-MM-DD */
  dueDate: string;
  /** รอบเดือน YYYY-MM */
  cycleMonth: string;
  /** เลยกำหนดแล้ว (ครบกำหนดก่อนวันนี้และยังไม่จ่าย) */
  overdue: boolean;
}

/** บิลที่ข้อมูลผิดรูป (แยกออกมาเพื่อแจ้งผู้ใช้ แทนที่จะทำให้ทั้งการ์ดพัง) */
export interface BillProblem {
  id: string;
  name: string;
  reason: string;
}
