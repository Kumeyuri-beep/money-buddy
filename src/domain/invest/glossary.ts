/**
 * คำอธิบายศัพท์การลงทุนภาษาคน (เจ้าของสั่ง 14 พ.ย. 2569): ใช้กับปุ่ม "ความหมาย" ที่แตะแล้วเห็นคำอธิบาย (ไม่ใช่ hover อย่างเดียว)
 * ข้อความอธิบายหลักการทั่วไป ไม่ใช่คำแนะนำด้านภาษี · ไม่เกี่ยวกับการคำนวณเงิน
 */
export const GLOSSARY = {
  'ปันผลเป็นเงินสด': 'กองทุนหรือบริษัทแบ่งกำไรมาให้เป็นเงิน เงินเข้ากระเป๋าของคุณ (หลังหักภาษีถ้ามี) จำนวนหน่วยที่ถืออยู่ไม่เปลี่ยน',
  'ปันผลลงทุนต่อ': 'ผู้จ่ายปันผลนำปันผลไปซื้อหน่วยเพิ่มให้เลย คุณไม่ได้รับเป็นเงิน แต่จำนวนหน่วยที่ถือเพิ่มขึ้น',
  'ภาษีหัก ณ ที่จ่าย': 'ภาษีที่ผู้จ่ายปันผลหักไว้ให้ก่อนโอนเงินเข้าบัญชี คุณจึงได้รับเงินน้อยกว่ายอดปันผลเท่าจำนวนนี้ ควรเก็บหลักฐานไว้เผื่อใช้ตอนยื่นภาษี',
} as const;

export type GlossaryTerm = keyof typeof GLOSSARY;

/** ศัพท์ที่มีคำอธิบาย (null = ไม่มี) */
export function glossaryText(term: string): string | null {
  return term in GLOSSARY ? GLOSSARY[term as GlossaryTerm] : null;
}
